//! `AGENTS.md` (APP-033): the guide for AI agents, built from the command registry of
//! this build plus hand-written text, so it never falls behind the installed app.
//!
//! - `agents/guide.md`: the hand-written guide; `<!-- commands -->` marks where the
//!   command list goes.
//! - `agents/commands.md`: an optional example and explanation per command.
//! - The registry ([`crate::catalog::specs`]) gives every command, its parameters, its
//!   flags and, when it has no note, its one-line English description.
//!
//! `xcreenshot agents-md` prints it, the MCP resource `xcreenshot://agents` serves it,
//! and the repository's `AGENTS.md` is this output (a test compares them).

use std::collections::HashMap;

use serde_json::Value;

use crate::catalog;
use crate::command::{CommandSpec, Scope};
use crate::i18n::{tr, Lang};

const GUIDE: &str = include_str!("../agents/guide.md");
const NOTES: &str = include_str!("../agents/commands.md");
const MARKER: &str = "<!-- commands -->";

/// A command's hand-written example and explanation.
#[derive(Debug, Clone, PartialEq)]
pub struct Note {
    pub example: String,
    pub text: String,
}

/// The notes by command ID, from the table in `agents/commands.md`.
pub fn notes() -> HashMap<String, Note> {
    let mut out = HashMap::new();
    for line in NOTES.lines() {
        let Some(row) = line.strip_prefix("| `") else {
            continue;
        };
        let row = row.trim_end().trim_end_matches('|').trim_end();
        let cells: Vec<&str> = row.splitn(3, " | ").collect();
        let [id, example, text] = cells[..] else {
            continue;
        };
        let id = id.trim_end_matches('`');
        out.insert(
            id.to_string(),
            Note {
                example: example.trim().to_string(),
                text: text.trim().to_string(),
            },
        );
    }
    out
}

/// The whole guide, in English.
pub fn render() -> String {
    let specs = catalog::specs();
    let notes = notes();
    let mut list = String::new();
    let mut areas: Vec<&str> = Vec::new();
    for s in &specs {
        if !areas.contains(&s.area()) {
            areas.push(s.area());
        }
    }
    for (i, area) in areas.iter().enumerate() {
        if i > 0 {
            list.push('\n');
        }
        list.push_str(&format!("### {area}\n\n"));
        list.push_str("| ID | Example | Parameters | What it does |\n|---|---|---|---|\n");
        for s in specs.iter().filter(|s| s.area() == *area) {
            list.push_str(&row(s, notes.get(s.id)));
        }
    }
    let banner = "<!-- Generated by `xcreenshot agents-md` from the command registry \
                  and crates/xs-core/agents/. Edit those, not this file. -->\n\n";
    let body = GUIDE.replacen(MARKER, list.trim_end(), 1);
    format!("{banner}{body}")
}

fn row(s: &CommandSpec, note: Option<&Note>) -> String {
    let example = match note {
        Some(n) => n.example.clone(),
        None => example(s),
    };
    let text = match note {
        Some(n) => n.text.clone(),
        None => cell(&tr(Lang::En, &format!("{}.description", s.i18n_base()), &[])),
    };
    let flags = flags(s);
    let text = if flags.is_empty() {
        text
    } else {
        format!("{text} _{flags}_")
    };
    format!("| `{}` | {} | {} | {} |\n", s.id, example, parameters(s), text)
}

/// `xcreenshot <area> <action> <positional…>` for a command without a note.
fn example(s: &CommandSpec) -> String {
    if !s.has_scope(Scope::Cli) {
        return if s.has_scope(Scope::Mcp) {
            "(MCP only)".to_string()
        } else {
            "(UI only)".to_string()
        };
    }
    let mut parts = vec![
        "xcreenshot".to_string(),
        s.area().to_string(),
        s.action().replace('_', "-"),
    ];
    for p in s.positional {
        parts.push(format!("<{p}>"));
    }
    if s.destructive {
        parts.push("--yes".to_string());
    }
    format!("`{}`", parts.join(" "))
}

/// The parameters from the schema: name, type or values, and whether required.
fn parameters(s: &CommandSpec) -> String {
    let Some(props) = s.params.get("properties").and_then(Value::as_object) else {
        return "—".to_string();
    };
    if props.is_empty() {
        return "—".to_string();
    }
    let required: Vec<&str> = s
        .params
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut out = Vec::new();
    for (name, schema) in props {
        let mut item = format!("`{name}`");
        let kind = kind(schema);
        if !kind.is_empty() {
            item.push(' ');
            item.push_str(&kind);
        }
        let mut marks = Vec::new();
        if required.contains(&name.as_str()) {
            marks.push("required");
        }
        if s.positional.contains(&name.as_str()) {
            marks.push("positional");
        }
        if !marks.is_empty() {
            item.push_str(&format!(" ({})", marks.join(", ")));
        }
        out.push(item);
    }
    out.join("; ")
}

/// The values of an enum, or the JSON type.
fn kind(schema: &Value) -> String {
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        let shown: Vec<String> = values
            .iter()
            .take(12)
            .map(|v| match v {
                Value::String(s) => format!("`{s}`"),
                other => format!("`{other}`"),
            })
            .collect();
        let more = if values.len() > 12 { " \\| …" } else { "" };
        return format!("{}{more}", shown.join(" \\| "));
    }
    let types: Vec<&str> = match schema.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    if types.is_empty() {
        if let Some(any) = schema.get("oneOf").or_else(|| schema.get("anyOf")) {
            let kinds: Vec<String> = any
                .as_array()
                .map(|a| a.iter().map(kind).filter(|k| !k.is_empty()).collect())
                .unwrap_or_default();
            return kinds.join(" or ");
        }
        return String::new();
    }
    types.join(" or ")
}

/// What the registry says about a command's effects.
fn flags(s: &CommandSpec) -> String {
    let mut out = Vec::new();
    if s.destructive {
        out.push("Destructive: the CLI needs `--yes`.");
    } else if s.mutates {
        out.push("Changes data.");
    } else {
        out.push("Changes no data.");
    }
    if s.interactive {
        out.push("May wait for the user.");
    }
    if s.network {
        out.push("Uses the network.");
    }
    if s.has_scope(Scope::Cli) && !s.has_scope(Scope::Mcp) {
        out.push("Not an MCP tool.");
    }
    out.join(" ")
}

/// Text for a table cell: one line, pipes escaped.
fn cell(s: &str) -> String {
    s.replace('\n', " ").replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// APP-033: every registered command is in the guide, and every note belongs to a
    /// registered command.
    #[test]
    fn the_guide_lists_every_command_and_no_stale_note() {
        let text = render();
        assert!(!text.contains(MARKER));
        let specs = catalog::specs();
        for s in &specs {
            assert!(text.contains(&format!("| `{}` |", s.id)), "{} missing", s.id);
        }
        for id in notes().keys() {
            assert!(
                specs.iter().any(|s| s.id == id),
                "agents/commands.md has a note for `{id}`, which is not a command"
            );
        }
    }

    /// The repository's AGENTS.md is the generated guide. To refresh it after a change
    /// to the registry or the notes: `XS_REGEN_AGENTS=1 cargo test -p xs-core agents`.
    #[test]
    fn agents_md_in_the_repository_is_current() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../AGENTS.md");
        let text = render();
        if std::env::var_os("XS_REGEN_AGENTS").is_some() {
            std::fs::write(path, &text).unwrap();
        }
        let file = std::fs::read_to_string(path).unwrap().replace("\r\n", "\n");
        assert!(
            file == text,
            "AGENTS.md is out of date: run XS_REGEN_AGENTS=1 cargo test -p xs-core agents"
        );
    }

    #[test]
    fn parameters_show_types_values_and_marks() {
        let specs = catalog::specs();
        let set = specs.iter().find(|s| s.id == "shortcuts.set").unwrap();
        let p = parameters(set);
        assert!(p.contains("`command` string (required, positional)"), "{p}");
        assert!(p.contains("`global` \\| `app` \\| `editor`"), "{p}");
        let ping = specs.iter().find(|s| s.id == "app.ping").unwrap();
        assert_eq!(parameters(ping), "—");
    }
}
