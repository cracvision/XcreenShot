// Simplify automatically (SMT-019): the Simplify tool covers text lines with bars and
// interface elements with shapes of its palette. Generating again after the user
// changed some of those objects asks first.
import { create } from "zustand";
import { run } from "../lib/commands";
import type { DocObject } from "./state";
import { useEditor } from "./state";

interface Result {
  needsConfirm?: boolean;
  edited?: number;
  kept?: number;
}

interface AutoSimplify {
  /** Waiting for "Generate again?": with what detail, and how many would be lost. */
  confirm: { documentId: string; detail: number; edited: number } | null;
  busy: boolean;
  /** Switched off, how many changed objects stayed. */
  kept: number;
}

export const useAutoSimplify = create<AutoSimplify>(() => ({
  confirm: null,
  busy: false,
  kept: 0,
}));

export const DEFAULT_DETAIL = 5;

/** Generated by auto simplify: on, and with what detail. */
export function autoState(objects: DocObject[]): { on: boolean; detail: number } {
  const generated = objects.filter(
    (o): o is Extract<DocObject, { type: "simplify" }> =>
      o.type === "simplify" && o.autoSimplify !== undefined,
  );
  return {
    on: generated.length > 0,
    detail: generated.find((o) => o.autoSimplify?.detail)?.autoSimplify?.detail ?? DEFAULT_DETAIL,
  };
}

async function simplify(params: Record<string, unknown>): Promise<Result | null> {
  useAutoSimplify.setState({ busy: true });
  try {
    return await run<Result>("smart.simplify_auto", params);
  } catch (e) {
    useEditor.getState().showError(e);
    return null;
  } finally {
    useAutoSimplify.setState({ busy: false });
  }
}

/** Generates the objects with `detail`; asks first when changes would be lost. */
export async function autoSimplify(documentId: string, detail: number): Promise<void> {
  useAutoSimplify.setState({ kept: 0 });
  const r = await simplify({ documentId, detail });
  if (r?.needsConfirm) {
    useAutoSimplify.setState({ confirm: { documentId, detail, edited: r.edited ?? 0 } });
  }
}

export async function confirmRegenerate(): Promise<void> {
  const c = useAutoSimplify.getState().confirm;
  useAutoSimplify.setState({ confirm: null });
  if (c) await simplify({ documentId: c.documentId, detail: c.detail, force: true });
}

export function cancelRegenerate(): void {
  useAutoSimplify.setState({ confirm: null });
}

/** Switched off: the generated objects the user did not change go. */
export async function autoSimplifyOff(documentId: string): Promise<void> {
  const r = await simplify({ documentId, remove: true });
  useAutoSimplify.setState({ kept: r?.kept ?? 0 });
}
